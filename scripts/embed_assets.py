#!/usr/bin/env python3
"""Regenerate python/vlambda/assets.py from ui.html, static/app.js and favicon.ico."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UI = (ROOT / "python/vlambda/ui.html").read_text(encoding="utf-8")
APP = (ROOT / "python/vlambda/static/app.js").read_bytes()
FAVICON = (ROOT / "python/vlambda/favicon.ico").read_bytes()
DOCS = (ROOT / "python/vlambda/docs.html").read_text(encoding="utf-8")

OUT = f'''"""Generated by scripts/embed_assets.py. Do not edit by hand."""

import mimetypes

UI_HTML = {UI!r}

APP_JS = {APP!r}

FAVICON = {FAVICON!r}

DOCS_HTML = {DOCS!r}


def get_asset(name: str) -> bytes | None:
    if name == "app.js":
        return APP_JS
    if name == "favicon.ico":
        return FAVICON
    if name == "docs.html":
        return DOCS_HTML.encode("utf-8")
    return None


def asset_content_type(name: str) -> str:
    ctype, _ = mimetypes.guess_type(name)
    return ctype or "application/octet-stream"
'''

(ROOT / "python/vlambda/assets.py").write_text(OUT, encoding="utf-8")
print(f"wrote python/vlambda/assets.py ({len(OUT)} bytes)")
