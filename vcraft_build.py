"""The PEP 517 backend for vcraft.

Generated by `vcraft new` and rewritten on every build. Do not edit.

Every hook here runs the `vcraft` binary and returns the path of what it
wrote, which is what PEP 517 asks for. The build itself happens in the
binary: this file locates it, runs it, and reports the result.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys


def _vcraft() -> str:
    """Return the vcraft binary, preferring one on PATH over a sibling.

    A checkout has `bin/vcraft` next to the project and no installed copy, and
    the binary in the tree is the one whose behaviour matches the backend.
    """
    override = os.environ.get("VCRAFT_BIN")
    if override and os.path.exists(override):
        return override
    sibling = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "bin", "vcraft")
    if os.path.exists(sibling):
        return sibling
    found = shutil.which("vcraft")
    if found:
        return found
    raise RuntimeError(
        "vcraft is not on PATH; put it there, set VCRAFT_BIN, or build from a checkout"
    )


def _run(*args: str, cwd: str | None = None) -> str:
    """Run vcraft and return the last line of its output, which is the path.

    The last line is the contract: `vcraft build` and `vcraft sdist` both end with
    the artefact they wrote, so a backend does not have to guess at a name.
    """
    env = dict(os.environ)
    # The backend may be invoked from a copy of the project that is not a
    # checkout of this tool, so the binary has to be named rather than inferred
    # from where the project sits.
    env.setdefault("VCRAFT_BIN", _vcraft())
    result = subprocess.run([_vcraft(), *args], capture_output=True, text=True, env=env, cwd=cwd)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or result.stdout.strip())
    lines = [line for line in result.stdout.strip().splitlines() if line.strip()]
    if not lines:
        raise RuntimeError("vcraft produced no output")
    # The artefact is the only line ending in the extension it built. Taking the
    # last line instead picks up the summary vcraft prints after it, and PEP 517
    # then tries to open a wheel whose name is a file size.
    for line in lines:
        if line.endswith(".whl") or line.endswith(".tar.gz"):
            # `vcraft build` announces its result as `built <path>`: the frontend
            # needs the path alone, and joining `built ...` onto a directory gives
            # a file that was never written.
            if line.startswith("built "):
                return line[len("built "):]
            return line
    return lines[-1]


def _project_root() -> str:
    """Return the source tree this backend file lives in.

    PEP 660 has to know where the project is, rather than where the frontend
    asked for the wheel: the wheel it returns must point at build output that
    survives the install, and output inside the frontend-chosen directory does
    not. A path derived from the working directory would also be wrong when
    pip copies the tree before it builds.
    """
    return os.path.dirname(os.path.abspath(__file__))


def _dist_info_from_wheel(wheel_path: str, metadata_directory: str) -> str:
    """Copy one wheel’s .dist-info into a metadata directory.

    Shared by the two metadata hooks, so the regular and editable answers
    cannot disagree about the metadata format.
    """
    import zipfile

    # A wheel name is `name-version-tag-tag-platform.whl`, so the
    # distribution and version are everything before the last three parts.
    # rsplit with a count of two stops one short and yields
    # `name-version-cp314`, which pip then reads as the *version* and rejects
    # with "Invalid version".
    dist_info = os.path.basename(wheel_path)[:-len(".whl")].rsplit("-", 3)[0]
    dist_info += ".dist-info"
    target = os.path.join(metadata_directory, dist_info)
    os.makedirs(target, exist_ok=True)
    with zipfile.ZipFile(wheel_path) as archive:
        for entry in archive.namelist():
            if ".dist-info/" not in entry:
                continue
            out = os.path.join(target, entry.split(".dist-info/", 1)[1])
            os.makedirs(os.path.dirname(out), exist_ok=True)
            with archive.open(entry) as src, open(out, "wb") as dst:
                dst.write(src.read())
    return dist_info


def build_wheel(wheel_directory, config_settings=None, metadata_directory=None) -> str:
    """Build a wheel and return its file name, which is what PEP 517 wants.

    PEP 517 asks for the *name*, not the path, and pip joins it onto the
    directory it chose. Returning the full path makes pip join it a second
    time, and the resulting error names a path with the directory inside
    itself.
    """
    produced = _run("build", "--release", "--out-dir", wheel_directory)
    return os.path.basename(produced)


def build_sdist(sdist_directory, config_settings=None) -> str:
    produced = _run("sdist", "--out-dir", sdist_directory)
    return os.path.basename(produced)


def get_requires_for_build_wheel(config_settings=None) -> list[str]:
    # vcraft compiles through V and links nothing, so there is nothing to install
    # before the build. The compiler itself is a host tool rather than a Python
    # dependency, and PEP 517 has no way to ask for one.
    return []


def get_requires_for_build_sdist(config_settings=None) -> list[str]:
    return []


def prepare_metadata_for_build_wheel(metadata_directory, config_settings=None) -> str:
    """Return the .dist-info directory name, as PEP 517 requires.

    The hook is optional and PEP 517 allows a backend to leave it out, but pip
    calls it when it is there and uses the answer without checking that it is a
    string. Returning None gives a TypeError deep inside pip's os.path.join,
    with nothing in the traceback pointing at this line.

    So the metadata comes from building the wheel and lifting the .dist-info out
    of it. That is wasteful for a frontend which wanted to skip the build, and
    cheaper than a second implementation of the metadata that would eventually
    disagree with the first.
    """
    import glob
    import tempfile

    with tempfile.TemporaryDirectory() as staging:
        _run("build", "--release", "--out-dir", staging)
        built = glob.glob(os.path.join(staging, "*.whl"))
        if not built:
            raise RuntimeError("vcraft produced no wheel")
        return _dist_info_from_wheel(built[0], metadata_directory)


def build_editable(wheel_directory, config_settings=None, metadata_directory=None) -> str:
    """Build an editable wheel and return its file name.

    The wheel is staged into the frontend-chosen directory, but it is built
    into `.vcraft/editable` under the source tree. An editable wheel points at
    build output by absolute path, and output in a temporary directory would
    point at a directory the installer has already removed.
    """
    project = _project_root()
    staging = os.path.join(project, ".vcraft", "editable")
    produced = _run("build", "--editable", "--release", "--out-dir", staging, cwd=project)
    name = os.path.basename(produced)
    shutil.copy(produced, os.path.join(wheel_directory, name))
    return name


def get_requires_for_build_editable(config_settings=None) -> list[str]:
    return []


def prepare_metadata_for_build_editable(metadata_directory, config_settings=None) -> str:
    """Return the .dist-info directory name for an editable install.

    The wheel is built for real, for the same reason as the regular hook: there
    is only one implementation of the metadata, so the editable answer cannot
    drift from it.
    """
    import glob
    import tempfile

    with tempfile.TemporaryDirectory() as staging:
        name = build_editable(staging)
        return _dist_info_from_wheel(os.path.join(staging, name), metadata_directory)
