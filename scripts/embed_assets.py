#!/usr/bin/env python3
"""Regenerate python/vlambda/assets.py from the UI sources."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "python/vlambda/static"
UI = (ROOT / "python/vlambda/ui.html").read_text(encoding="utf-8")
APP = (STATIC / "app.js").read_bytes()
APP_UI = (STATIC / "ui.js").read_bytes()
APP_CSS = (STATIC / "ui.css").read_bytes()
FAVICON = (ROOT / "python/vlambda/favicon.ico").read_bytes()

OUT = f'''"""Generated by scripts/embed_assets.py. Do not edit by hand."""

import mimetypes

UI_HTML = {UI!r}

APP_JS = {APP!r}

UI_JS = {APP_UI!r}

UI_CSS = {APP_CSS!r}

FAVICON = {FAVICON!r}


def get_asset(name: str) -> bytes | None:
    if name == "app.js":
        return APP_JS
    if name == "ui.js":
        return UI_JS
    if name == "ui.css":
        return UI_CSS
    if name == "favicon.ico":
        return FAVICON
    return None


def asset_content_type(name: str) -> str:
    ctype, _ = mimetypes.guess_type(name)
    return ctype or "application/octet-stream"
'''

(ROOT / "python/vlambda/assets.py").write_text(OUT, encoding="utf-8")
print(f"wrote python/vlambda/assets.py ({len(OUT)} bytes)")
